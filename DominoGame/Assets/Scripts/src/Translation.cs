    public static string GetTranslation(StringType key)
    {
        string currentLanguageCode = LocalizationSettings.SelectedLocale.Identifier.Code;
        if (Messages.ContainsKey(currentLanguageCode) && Messages[currentLanguageCode].ContainsKey(key))
        {
            return Messages[currentLanguageCode][key];
        }

        return key.ToString();
    }

    public static string GetTranslationError(ErrorTypes error)
    {
        if (ErrorTypeToStringTypeMap.TryGetValue(error, out StringType stringType))
        {
            return GetTranslation(stringType);
        }
        
        return StringType.Unknown.ToString();
    }
